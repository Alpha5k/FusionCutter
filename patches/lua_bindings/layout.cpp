const Layout *select_layout(std::string_view profile) noexcept {
    for (const auto &layout : kLayouts) {
        if (layout.profile == profile) {
            return &layout;
        }
    }

    return nullptr;
}

fc::Evidence instruction_evidence(const NativeSite &site, std::uintptr_t image_base) {
    auto evidence = fc::exact_bytes(site.bytes);
    if (site.target_rva) {
        // These x86 instructions contain a four-byte absolute address; relocation changes only that operand.
        const auto address = static_cast<std::uint32_t>(image_base + site.target_rva);
        std::memcpy(evidence.bytes.data() + site.operand_offset, &address, sizeof(address));
    }

    return evidence;
}


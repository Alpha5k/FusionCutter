// Selects one retail build's explicit addresses while preserving helper order and shared evidence.
constexpr std::array<NativeSite, Layout::kFunctionCount> retail_functions(bool steam) {
    std::array<NativeSite, Layout::kFunctionCount> result{};
    for (std::size_t index = 0; index < result.size(); ++index) {
        const auto &site = kRetailFunctions[index];
        result[index] = {steam ? site.steam_rva : site.gog_rva, site.name, site.bytes};
    }
    return result;
}

constexpr auto kGogFunctions = retail_functions(false);
constexpr auto kSteamFunctions = retail_functions(true);

